#!/usr/bin/env bash
set -euo pipefail

export DUUI_REMOVE_ANNOTATIONS_ANNOTATOR_NAME=duui-remove-annotations
export DUUI_REMOVE_ANNOTATIONS_ANNOTATOR_VERSION=1.0.0

export DUUI_REMOVE_ANNOTATIONS_LOG_LEVEL=INFO

export DOCKER_REGISTRY="docker.texttechnologylab.org/"

docker build \
  --build-arg DUUI_REMOVE_ANNOTATIONS_ANNOTATOR_NAME \
  --build-arg DUUI_REMOVE_ANNOTATIONS_ANNOTATOR_VERSION \
  --build-arg DUUI_REMOVE_ANNOTATIONS_LOG_LEVEL \
  -t ${DOCKER_REGISTRY}${DUUI_REMOVE_ANNOTATIONS_ANNOTATOR_NAME}:${DUUI_REMOVE_ANNOTATIONS_ANNOTATOR_VERSION} \
  -f "src/main/docker/Dockerfile" \
  .

docker tag \
  ${DOCKER_REGISTRY}${DUUI_REMOVE_ANNOTATIONS_ANNOTATOR_NAME}:${DUUI_REMOVE_ANNOTATIONS_ANNOTATOR_VERSION} \
  ${DOCKER_REGISTRY}${DUUI_REMOVE_ANNOTATIONS_ANNOTATOR_NAME}:latest
